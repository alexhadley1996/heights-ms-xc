/* Heights MS XC — draft site logic. Data comes from data/results.js (window.XC_DATA),
   generated by scripts/build_data.py from the team's results sheet. */
(function () {
  const D = window.XC_DATA;
  const meetsById = Object.fromEntries(D.meets.map(m => [m.id, m]));
  const runnersById = Object.fromEntries(D.runners.map(r => [r.id, r]));
  const chrono = (a, b) => a.season - b.season || a.order - b.order;
  const seasons = [...new Set(D.meets.map(m => m.season))].sort((a, b) => b - a);
  const $ = s => document.querySelector(s);
  const esc = s => String(s ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const qs = k => new URLSearchParams(location.search).get(k);
  const dash = '<span class="muted">—</span>';
  const v = x => (x === null || x === undefined || x === "") ? dash : esc(x);
  const ord = n => { const s = ["th", "st", "nd", "rd"], v = n % 100; return n + (s[(v - 20) % 10] || s[v] || s[0]); };
  const meetLink = m => `meet.html?id=${encodeURIComponent(m.id)}`;
  const runnerLink = name => { const r = D.runners.find(x => x.name === name); return r ? `runner.html?id=${encodeURIComponent(r.id)}` : null; };
  const meetTitle = m => `${m.season} ${m.name}${m.date ? " (" + m.date + ")" : ""}`;
  const distText = m => m.distance ? `${m.distance} mi` : (m.impliedDistance ? `≈${m.impliedDistance} mi <span class="muted" title="Not stated in the sheet; estimated from time ÷ pace">(est.)</span>` : "Distance not recorded");
  const heightsOf = m => m.results.filter(e => e.heights);

  // ---------- shell ----------
  const page = document.body.dataset.page;
  const nav = [["index.html", "Home", "home"], ["meets.html", "Meets", "meets"], ["runners.html", "Runners", "runners"], ["top.html", "Top Times", "top"], ["history.html", "History", "history"]];
  document.body.insertAdjacentHTML("afterbegin", `
    <header class="site"><div class="wrap">
      <a class="brand" href="index.html"><img src="assets/heights-crest.svg" alt="The Heights School crest"><span class="bt"><span class="school">The Heights School</span><span class="team">Middle School Cross Country</span></span></a>
      <nav class="main">${nav.map(([h, t, k]) => `<a href="${h}" class="${k === page || (page === "meet" && k === "meets") || (page === "runner" && k === "runners") ? "active" : ""}">${t}</a>`).join("")}</nav>
    </div></header>`);
  document.body.insertAdjacentHTML("beforeend", `
    <footer><div class="wrap"><img src="assets/heights-crest.svg" alt=""><div>Results compiled from the team's results spreadsheet (data refreshed ${esc(D.generated)}).
    Highlighted rows are Heights runners. Spot an error or have an old result sheet? <!-- PLACEHOLDER: contact info -->[Contact placeholder]</div></div></footer>`);

  // ---------- helpers ----------
  function resultsTable(rows, opts = {}) {
    const showPace = rows.some(r => r.pace);
    const showGrade = rows.some(r => r.grade);
    const head = `<tr>${opts.heightsPlace ? '<th class="num">Heights</th>' : ""}<th class="num">Place</th>${showGrade ? '<th class="num hide-sm">Gr</th>' : ""}<th>Name</th>${opts.school ? '<th class="hide-sm">School</th>' : ""}<th class="num">Time</th>${showPace ? '<th class="num">Pace/mi</th>' : ""}${opts.gap ? '<th class="num hide-sm">Gap</th>' : ""}</tr>`;
    const lead = rows.find(r => r.secs)?.secs;
    const body = rows.map(r => {
      const link = r.heights ? runnerLink(r.name) : null;
      const name = link ? `<a href="${link}">${esc(r.name)}</a>` : esc(r.name);
      const gap = opts.gap && r.secs && lead ? (r.secs === lead ? "—" : "+" + fmt(r.secs - lead)) : "";
      return `<tr class="${r.heights && opts.mark ? "heights" : ""}">${opts.heightsPlace ? `<td class="num">${v(r.hplace)}</td>` : ""}<td class="num">${v(r.place)}</td>${showGrade ? `<td class="num hide-sm">${v(r.grade)}</td>` : ""}<td>${name}${r.note ? ` <span class="badge ghost" title="${esc(r.note)}">note</span>` : ""}${r.suspect ? ` <span class="badge ghost" title="Time is faster than runners placed ahead of this runner in the sheet; time or place was probably mis-entered">check</span>` : ""}</td>${opts.school ? `<td class="hide-sm">${v(r.school)}</td>` : ""}<td class="num t">${v(r.time)}</td>${showPace ? `<td class="num">${v(r.pace)}</td>` : ""}${opts.gap ? `<td class="num hide-sm muted">${gap}</td>` : ""}</tr>`;
    }).join("");
    return `<div class="table-wrap"><table><thead>${head}</thead><tbody>${body || `<tr><td colspan="8" class="muted">No results.</td></tr>`}</tbody></table></div>`;
  }
  function fmt(s) { const m = Math.floor(s / 60), r = s - m * 60; return `${m}:${r.toFixed(1).padStart(4, "0")}`; }
  function meetCard(m) {
    const h = heightsOf(m).filter(e => e.secs).slice(0, 3);
    return `<a class="card meet-card" href="${meetLink(m)}">
      <div class="season">${m.season}${m.date ? " · " + esc(m.date) : ""}</div>
      <h3>${esc(m.name)}</h3>
      <div class="meta"><span>${m.heightsCount} Heights runners</span><span>${m.fieldSize} total in field</span><span>${distText(m)}</span></div>
      <ul class="top3">${h.map(e => `<li><span>${e.hplace}. ${esc(e.name)}</span><span>${esc(e.time)}</span></li>`).join("")}</ul></a>`;
  }

  // ---------- pages ----------
  const pages = {
    home() {
      const latest = seasons[0];
      const totalResults = D.meets.reduce((a, m) => a + m.heightsCount, 0);
      $("#app").innerHTML = `
      <section class="hero"><div class="wrap">
        <img class="crest" src="assets/heights-crest.svg" alt="The Heights School crest"><div class="hero-text">
        <div class="eyebrow">The Heights School Cavaliers · Middle School</div>
        <h1>Cross Country<br>Results &amp; Records</h1>
        <p>Race-by-race results for Heights middle school runners, from ${seasons[seasons.length - 1]} through ${latest}.</p>
        <div class="stats">
          <div class="stat"><b>${seasons.length}</b><span>seasons on record</span></div>
          <div class="stat"><b>${D.meets.length}</b><span>races</span></div>
          <div class="stat"><b>${D.runners.length}</b><span>Heights runners</span></div>
          <div class="stat"><b>${totalResults}</b><span>Heights finishes</span></div>
        </div>
      </div></div></section>
      <div class="wrap">
        <h2>${latest} season</h2>
        <div class="grid">${D.meets.filter(m => m.season === latest).sort(chrono).map(meetCard).join("")}</div>
        <h2>About the team</h2>
        <div class="placeholder"><strong>Placeholder — team overview</strong>Add a short introduction to the program here (coaches, practice, how to join). Nothing has been filled in yet.</div>
        <h2>All seasons</h2>
        <div class="grid">${seasons.map(s => { const ms = D.meets.filter(m => m.season === s).sort(chrono); return `<a class="card meet-card" href="meets.html#s${s}"><div class="season">Season</div><h3>${s}</h3><div class="meta"><span>${ms.length} race${ms.length > 1 ? "s" : ""}</span></div><ul class="top3">${ms.map(m => `<li><span>${esc(m.name)}${m.date ? " · " + esc(m.date) : ""}</span><span class="muted cnt" title="Heights runners in this race">${m.heightsCount} runners</span></li>`).join("")}</ul></a>`; }).join("")}</div>
        <p class="note">Seasons 2011–2020 are not in the results sheet yet.</p>
      </div>`;
    },
    meets() {
      $("#app").innerHTML = `<div class="wrap"><div class="page-head"><h1>Meets</h1><div class="sub">Every race in the results sheet, grouped by season. Within a season, races follow the sheet's tab order.</div></div>
        ${seasons.map(s => `<section class="season-block" id="s${s}"><h2>${s} <small>${D.meets.filter(m => m.season === s).length} races</small></h2><div class="grid">${D.meets.filter(m => m.season === s).sort(chrono).map(meetCard).join("")}</div></section>`).join("")}
        <h2>Data notes</h2><div class="card"><ul class="note" style="margin:0;padding-left:18px">${D.quirks.map(q => `<li>${esc(q)}</li>`).join("")}</ul></div></div>`;
      if (location.hash) document.querySelector(location.hash)?.scrollIntoView();
    },
    meet() {
      const m = meetsById[qs("id")] || D.meets[0];
      document.title = `${meetTitle(m)} · Heights MS XC`;
      const all = [...D.meets].sort(chrono), i = all.indexOf(m), prev = all[i - 1], next = all[i + 1];
      const h = heightsOf(m);
      const fin = h.filter(e => e.secs);
      $("#app").innerHTML = `<div class="wrap">
        <div class="page-head"><div class="crumbs"><a href="meets.html">Meets</a> / <a href="meets.html#s${m.season}">${m.season}</a></div>
        <h1>${esc(meetTitle(m))}</h1>
        <div class="sub">${distText(m)} · ${m.fieldSize} total in field · ${m.heightsCount} Heights runners${fin.length ? ` · Heights top finisher: ${ord(fin[0].place)} overall` : ""}</div></div>
        <div class="toolbar">
          <div class="seg" id="view"><button data-v="h" class="on">Heights runners</button><button data-v="all">Full field</button></div>
          <input type="search" id="q" placeholder="Search name or school…">
        </div>
        <div id="tbl"></div>
        <p class="note">Sheet tab: “${esc(m.tab)}”. “Heights” = place among Heights finishers in this race. ${!m.hasPace ? "No pace recorded for this race. " : ""}${!m.hasGrade ? "Grades not recorded for this race. " : ""}</p>
        <div class="toolbar">${prev ? `<a class="pill" href="${meetLink(prev)}">← ${esc(meetTitle(prev))}</a>` : ""}${next ? `<a class="pill" href="${meetLink(next)}">${esc(meetTitle(next))} →</a>` : ""}</div>
      </div>`;
      let mode = "h";
      const draw = () => {
        const q = $("#q").value.trim().toLowerCase();
        let rows = mode === "h" ? h : m.results;
        if (q) rows = rows.filter(r => (r.name + " " + r.school).toLowerCase().includes(q));
        $("#tbl").innerHTML = mode === "h" ? resultsTable(rows, { heightsPlace: true, gap: true }) : resultsTable(rows, { heightsPlace: true, school: true, mark: true });
      };
      $("#view").onclick = e => { const b = e.target.closest("button"); if (!b) return; mode = b.dataset.v; [...$("#view").children].forEach(x => x.classList.toggle("on", x === b)); draw(); };
      $("#q").oninput = draw; draw();
    },
    runners() {
      $("#app").innerHTML = `<div class="wrap"><div class="page-head"><h1>Runners</h1><div class="sub">${D.runners.length} Heights runners appear in the results. Search by name, or filter by season.</div></div>
        <div class="toolbar"><input type="search" id="q" placeholder="Search runners…" autofocus>
          <select id="season"><option value="">All seasons</option>${seasons.map(s => `<option>${s}</option>`).join("")}</select>
          <select id="sort"><option value="name">Sort: last name</option><option value="pace">Sort: best pace</option><option value="races">Sort: most races</option></select></div>
        <div id="list" class="runner-list"></div><p class="note" id="count"></p></div>`;
      const draw = () => {
        const q = $("#q").value.trim().toLowerCase(), s = +$("#season").value, sort = $("#sort").value;
        let rs = D.runners.filter(r => r.name.toLowerCase().includes(q) && (!s || r.seasons.includes(s)));
        if (sort === "pace") rs = [...rs].sort((a, b) => (a.bestPaceSecs ?? 1e9) - (b.bestPaceSecs ?? 1e9));
        if (sort === "races") rs = [...rs].sort((a, b) => b.results.length - a.results.length);
        $("#list").innerHTML = rs.map(r => `<a href="runner.html?id=${encodeURIComponent(r.id)}"><span><b>${esc(r.name)}</b><br><span class="yrs">${r.seasons.join(", ")} · ${r.results.length} race${r.results.length > 1 ? "s" : ""}</span></span><span class="t muted" title="Best pace per mile">${r.bestPace ? esc(r.bestPace) + "/mi" : ""}</span></a>`).join("") || '<p class="muted">No runners match.</p>';
        $("#count").textContent = `${rs.length} shown`;
      };
      ["#q", "#season", "#sort"].forEach(id => $(id).oninput = draw); draw();
    },
    runner() {
      const r = runnersById[qs("id")];
      if (!r) { $("#app").innerHTML = `<div class="wrap"><div class="page-head"><h1>Runner not found</h1><a href="runners.html">Back to runners</a></div></div>`; return; }
      document.title = `${r.name} · Heights MS XC`;
      const res = r.results.map(x => ({ ...x, m: meetsById[x.meet] })).sort((a, b) => chrono(a.m, b.m));
      const best = res.filter(x => x.paceSecs && !x.suspect).sort((a, b) => a.paceSecs - b.paceSecs)[0];
      const seasonBest = {};
      res.forEach(x => { if (x.paceSecs && !x.suspect && (!seasonBest[x.m.season] || x.paceSecs < seasonBest[x.m.season].paceSecs)) seasonBest[x.m.season] = x; });
      const bestPlace = res.filter(x => typeof x.place === "number").sort((a, b) => a.place - b.place)[0];
      const grades = [...new Set(res.map(x => x.grade).filter(Boolean))];
      $("#app").innerHTML = `<div class="wrap">
        <div class="page-head"><div class="crumbs"><a href="runners.html">Runners</a></div><h1>${esc(r.name)}</h1>
        <div class="sub">${r.seasons.join(", ")}${grades.length ? ` · grade${grades.length > 1 ? "s" : ""} ${grades.join(", ")}` : ""}</div></div>
        <div class="pbs">
          <div class="card"><span>Best pace</span><b>${best ? esc(best.pace) : "—"}</b><span>${best ? esc(meetTitle(best.m)) : "No pace recorded"}</span></div>
          <div class="card"><span>Time in PB race</span><b>${best ? esc(best.time) : esc(res.find(x => x.secs)?.time || "—")}</b><span>${best ? esc(best.m.name) + " · " + distText(best.m) : ""}</span></div>
          <div class="card"><span>Best overall place</span><b>${bestPlace ? ord(bestPlace.place) : "—"}</b><span>${bestPlace ? esc(meetTitle(bestPlace.m)) : ""}</span></div>
          <div class="card"><span>Races</span><b>${res.length}</b><span>in the results sheet</span></div>
        </div>
        <div class="table-wrap"><table><thead><tr><th>Season</th><th>Meet</th><th class="num">Gr</th><th class="num">Place</th><th class="num">Heights</th><th class="num">Time</th><th class="num">Pace/mi</th><th class="hide-sm">Distance</th></tr></thead><tbody>
        ${res.map(x => `<tr><td>${x.m.season}</td><td><a href="${meetLink(x.m)}">${esc(x.m.name)}${x.m.date ? " · " + esc(x.m.date) : ""}</a></td><td class="num">${v(x.grade)}</td><td class="num">${v(x.place)}</td><td class="num">${v(x.hplace)}</td><td class="num t">${v(x.time)}${x.suspect ? ' <span class="badge ghost" title="Time is out of order with the placings in the sheet; probably mis-entered">check</span>' : ""}</td><td class="num">${v(x.pace)}${x === best ? '<span class="badge" title="Personal best pace">PB</span>' : (seasonBest[x.m.season] === x && r.seasons.length > 1 ? '<span class="badge ghost" title="Season best pace">SB</span>' : "")}</td><td class="hide-sm muted">${distText(x.m)}</td></tr>`).join("")}
        </tbody></table></div>
        <p class="note">Courses and distances differ from meet to meet, so the personal best (PB) is the fastest <em>pace per mile</em>, not the lowest raw time. SB = season best pace.</p>
      </div>`;
    },
    top() {
      const raceOpts = [...D.meets].sort((a, b) => -chrono(a, b));
      $("#app").innerHTML = `<div class="wrap"><div class="page-head"><h1>Top Times</h1><div class="sub">Fastest Heights performances. Across different races, results are ranked by pace per mile because course lengths vary.</div></div>
        <div class="toolbar">
          <select id="race"><option value="">All races (ranked by pace)</option>${raceOpts.map(m => `<option value="${m.id}">${esc(meetTitle(m))}</option>`).join("")}</select>
          <select id="grade"><option value="">All grades</option><option>5</option><option>6</option><option>7</option><option>8</option></select>
          <select id="season"><option value="">All seasons</option>${seasons.map(s => `<option>${s}</option>`).join("")}</select>
          <select id="limit"><option>25</option><option selected>50</option><option>100</option><option value="0">All</option></select>
          <label class="chk"><input type="checkbox" id="one" checked> Best per runner</label>
        </div><div id="tbl"></div>
        <p class="note">Races without a recorded pace (2010 meets) only appear when chosen individually. Grade filter skips results where grade wasn't recorded. A few 2023 Flint Hill times that are out of order with the placings are left out.</p></div>`;
      const draw = () => {
        const race = $("#race").value, g = +$("#grade").value, s = +$("#season").value, lim = +$("#limit").value, one = $("#one").checked;
        let rows = [];
        D.meets.forEach(m => { if ((race && m.id !== race) || (s && m.season !== s)) return; heightsOf(m).forEach(e => rows.push({ ...e, m })); });
        rows = rows.filter(e => (race ? e.secs : e.paceSecs) && !e.suspect && (!g || e.grade === g));
        rows.sort(race ? (a, b) => a.secs - b.secs : (a, b) => a.paceSecs - b.paceSecs || a.secs - b.secs);
        if (one) { const seen = new Set(); rows = rows.filter(e => !seen.has(e.name) && seen.add(e.name)); }
        if (lim) rows = rows.slice(0, lim);
        $("#tbl").innerHTML = `<div class="table-wrap"><table><thead><tr><th class="num">#</th><th>Name</th><th class="num">Gr</th><th class="num">${race ? "Time" : "Pace/mi"}</th><th class="num">${race ? "Pace/mi" : "Time"}</th><th>Meet</th><th class="num hide-sm">Place</th></tr></thead><tbody>
        ${rows.map((e, i) => { const l = runnerLink(e.name); return `<tr><td class="num">${i + 1}</td><td><a href="${l}">${esc(e.name)}</a></td><td class="num">${v(e.grade)}</td><td class="num t">${v(race ? e.time : e.pace)}</td><td class="num">${v(race ? e.pace : e.time)}</td><td><a href="${meetLink(e.m)}">${esc(meetTitle(e.m))}</a></td><td class="num hide-sm">${v(e.place)}</td></tr>`; }).join("") || '<tr><td colspan="7" class="muted">No results.</td></tr>'}
        </tbody></table></div>`;
      };
      ["#race", "#grade", "#season", "#limit", "#one"].forEach(id => $(id).oninput = draw); draw();
    },
    history() {
      $("#app").innerHTML = `<div class="wrap"><div class="page-head"><h1>History</h1><div class="sub">The story of Heights middle school cross country.</div></div>
        <div class="placeholder"><strong>Placeholder — program history</strong>When did the team start, who coached it, and what were the milestone seasons? To be written.</div>
        <h2>Coaches</h2><div class="placeholder"><strong>Placeholder — coaches</strong>List of head coaches by year.</div>
        <h2>Championship highlights</h2><div class="placeholder"><strong>Placeholder — highlights</strong>Team titles, standout individual finishes, notable streaks.</div>
        <h2>Missing seasons</h2><div class="card">The results sheet currently has ${seasons.length} seasons: ${[...seasons].reverse().join(", ")}. Results for 2011–2020 (and anything before 2006) still need to be found.</div>
        <h2>Photos</h2><div class="placeholder"><strong>Placeholder — photo gallery</strong>Team photos by season.</div></div>`;
    },
  };
  (pages[page] || pages.home)();
})();
